import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { compareSnapshots, csv, emptyFilters, filterInventory, metrics } from "../src/lib/inventory.ts";

const source = readFileSync("../OneDrive_1_10-6-2026/Dataset Académico Parches en Servidores.xlsx");
const parsed = JSON.parse(execFileSync("python3", ["scripts/read-inventory.py"], { input: source, maxBuffer: 15 * 1024 * 1024 }));
const snapshot = { ...parsed, id: "baseline", name: "Baseline", hash: "test", referenceDate: null };
assert.deepEqual(metrics(filterInventory(snapshot, emptyFilters)), { servers: 246, findings: 3450, open: 2875, high: 561, overdue: 257, obsolete: 193, remediated: 575, exposed: 15 });
const closed = metrics(filterInventory(snapshot, { ...emptyFilters, status: "REMEDIATED" }));
assert.equal(closed.findings, 575);
assert.equal(closed.overdue, 0);
assert.equal(closed.open, 0);
const five = filterInventory(snapshot, { ...emptyFilters, severity: "5" });
assert.equal(five.findings.length, 170);
const highPending = filterInventory(snapshot, { ...emptyFilters, severity: "4_5", status: "OPEN" });
assert.equal(highPending.findings.length, 561);
assert.equal(metrics(highPending).high, 561);
assert.ok(five.findings.every(f => five.servers.some(s => s.ServerID === f.ServerID)));
const north = filterInventory(snapshot, { ...emptyFilters, region: "REGION_NORTH" });
assert.equal(north.servers.length, 131);
assert.ok(north.findings.every(f => north.servers.some(s => s.ServerID === f.ServerID)));
assert.equal(filterInventory(snapshot, { ...emptyFilters, search: "srv-0001" }).servers.length, 1);
assert.equal(filterInventory(snapshot, { ...emptyFilters, search: "no-existe-999" }).findings.length, 0);
const changed = structuredClone(snapshot);
const resolving = changed.findings.find(f => f.FindingStatus === "ACTIVE" && f.Severity === "4");
resolving.FindingStatus = "REMEDIATED";
const reopening = changed.findings.find(f => f.FindingStatus === "REMEDIATED" && f.FindingID !== resolving.FindingID);
reopening.FindingStatus = "REOPENED";
const absent = changed.findings.pop();
changed.findings.push({ ...absent, FindingID: "FND-NEW" });
const diff = compareSnapshots(snapshot, changed, emptyFilters);
assert.equal(diff.resolved.length, 1);
assert.equal(diff.reopened.length, 1);
assert.equal(diff.added.length, 1);
assert.equal(diff.absent.length, 1);
assert.equal(diff.absent[0].FindingID, absent.FindingID);
assert.notEqual(diff.resolved[0].FindingID, absent.FindingID);
assert.equal(compareSnapshots(snapshot, snapshot, emptyFilters).resolved.length, 0);
const safeCsv = csv([{ id: '=HYPERLINK("x")', note: 'quote " and , comma' }], ["id", "note"]);
assert.ok(safeCsv.includes("'="));
assert.ok(safeCsv.includes('quote "" and , comma'));
const noFindings = { ...snapshot, findings: [] };
assert.equal(filterInventory(noFindings, emptyFilters).servers.length, 246);
assert.equal(filterInventory(noFindings, { ...emptyFilters, severity: "5" }).servers.length, 0);
console.log("PASS: source metrics, joined filters, resolved/absent/reopened/new comparisons, empty inventory and CSV escaping.");
